// Regenerates bench/turf/csv.js from csv-src.mjs, taking every expected
// output from the Python reference (refs/<id>.py).
import { SRC } from './csv-src.mjs';
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const esc = s => JSON.stringify(s).replace(/[\u007f-￿]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
const run = (id, stdin) => {
  const r = spawnSync('python3', [join(here, 'refs', id + '.py')], { input: Buffer.from(stdin, 'utf8') });
  if (r.status !== 0) throw new Error(`${id}: python failed: ${r.stderr}`);
  return r.stdout.toString('utf8').replace(/\n$/, '');
};
let out = '// GENERATED by gen-csv.mjs from csv-src.mjs; expected outputs come from refs/<id>.py.\n// CSV-scripting arena: input on stdin, exact stdout (no trailing newline) in expect.\n\nexport const CSV_TASKS = [\n';
for (const t of SRC) {
  out += `  {\n    id: ${esc(t.id)},\n    name: ${esc(t.name)},\n    arena: 'csv',\n    spec: ${esc(t.spec)},\n    checks: [\n`;
  for (const c of t.checks) out += `      { stdin: ${esc(c.stdin)}, expect: ${esc(run(t.id, c.stdin))} },\n`;
  out += '    ],\n    hidden: [\n';
  for (const c of t.hidden) out += `      { stdin: ${esc(c.stdin)}, expect: ${esc(run(t.id, c.stdin))}, trap: ${esc(c.trap)} },\n`;
  out += '    ],\n  },\n';
}
out += '];\n';
writeFileSync(join(here, 'csv.js'), out);
console.log('wrote csv.js', SRC.map(t => `${t.id}: ${t.checks.length} visible / ${t.hidden.length} hidden`).join('; '));
