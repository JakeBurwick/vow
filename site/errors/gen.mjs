// Runs every case on the Errors page in Vow, TypeScript (deno check, then deno run) and Python,
// and writes what each one actually printed to cases.js. Nothing on that page is typed by hand.
//   node site/errors/gen.mjs
import { execFileSync } from 'node:child_process';
import { mkdtempSync, copyFileSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const here = new URL('.', import.meta.url).pathname;
const vowCli = join(here, '..', '..', 'cli.js');

const CASES = [
  { id: 'parse', title: 'Text that is not a number', task: 'Read a quantity from the command line and add 1.', arg: '12abc', want: 'error' },
  { id: 'key', title: 'A key that is not in the map', task: 'Look up a price by name and double it.', arg: 'pear', want: 'error' },
  { id: 'avg', title: 'Averaging an empty list', task: 'Average a comma-separated list of scores.', arg: '', want: 'error' },
  { id: 'typo', title: 'A misspelled field name', task: 'Print a user\'s email address.', arg: null, want: 'error' },
  { id: 'bigid', title: 'A large id in JSON', task: 'Print the id of an order read from JSON.', arg: '{"id": 9007199254740993}', want: 'order 9007199254740993' },
];

const RUN = {
  vow: (f, a) => [['node', [vowCli, f, ...a]]],
  ts: (f, a) => [['deno', ['check', '-q', f]], ['deno', ['run', '-q', f, ...a]]],
  py: (f, a) => [['python3', [f, ...a]]],
};

function run(lang, src, arg) {
  const dir = mkdtempSync(join(tmpdir(), 'vowerr-'));
  const file = `main.${lang}`;
  copyFileSync(src, join(dir, file));
  let out = '', code = 0, stage = 'run';
  for (const [i, [cmd, argv]] of RUN[lang](file, arg == null ? [] : [arg]).entries()) {
    try {
      out += execFileSync(cmd, argv, { cwd: dir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], env: { ...process.env, NO_COLOR: '1' } });
    } catch (e) {
      out += (e.stdout || '') + (e.stderr || '');
      code = e.status ?? 1;
      if (lang === 'ts' && i === 0) stage = 'check';
      break;
    }
  }
  rmSync(dir, { recursive: true, force: true });
  // shorten the temp folder so every path reads /work/main.<ext>
  out = out.split(dir).join('/work').replace(/\/private\/work/g, '/work').trimEnd();
  return { out, code, stage };
}

function outcome(lang, r, c) {
  if (c.want === 'error') {
    if (r.code === 0) return { label: `Printed ${JSON.stringify(r.out)}, exit 0`, good: false };
    const before = lang === 'vow' ? /^✗ TypeError/.test(r.out) : lang === 'ts' && r.stage === 'check';
    return { label: before ? 'Caught before running' : 'Stopped while running', good: true };
  }
  return r.code === 0 && r.out === c.want
    ? { label: 'Correct output', good: true }
    : { label: r.code === 0 ? `Wrong output, exit 0` : 'Stopped while running', good: false };
}

const cases = CASES.map((c) => ({
  ...c,
  langs: Object.fromEntries(['vow', 'ts', 'py'].map((lang) => {
    const src = join(here, `${c.id}.${lang}`);
    const r = run(lang, src, c.arg);
    return [lang, { code: readFileSync(src, 'utf8').trimEnd(), out: r.out, exit: r.code, ...outcome(lang, r, c) }];
  })),
}));

const versions = {
  vow: JSON.parse(readFileSync(join(here, '..', '..', 'package.json'), 'utf8')).version,
  deno: execFileSync('deno', ['--version'], { encoding: 'utf8' }).split('\n')[0].replace(/ \(.*/, ''),
  python: execFileSync('python3', ['--version'], { encoding: 'utf8' }).trim(),
};
const stamp = new Date().toISOString().slice(0, 10);
writeFileSync(join(here, 'cases.js'),
  `// GENERATED by site/errors/gen.mjs on ${stamp}. Do not edit by hand.\n` +
  `window.VOW_ERRORS = ${JSON.stringify({ measured: stamp, versions, cases }, null, 1)};\n`);
for (const c of cases) console.log(c.id.padEnd(6), Object.entries(c.langs).map(([l, x]) => `${l}: ${x.label}`).join(' | '));
